function [length_input,statistics] = Cable_length_error(nominal_length,total_samples,seed,standard_deviation,evaluation_idx)
assert(isscalar(nominal_length) && nominal_length>0);
assert(isscalar(standard_deviation) && standard_deviation>=0);
stream = RandStream('mt19937ar','Seed',seed);

epsilon_c = sqrt(3)*standard_deviation*(2*rand(stream,1,total_samples)-1);
length_input = nominal_length-epsilon_c;
assert(all(length_input>0),'Cable_length_error:NonpositiveLength', ...
    'A nonpositive cable-length sample occurred; no clipping or resampling was applied.');
statistics = struct('Model','Externally injected iid uniform cable-length error', ...
    'Seed',seed,'NominalLength_m',nominal_length,'ExpectedError_m',0, ...
    'Bounds_m',sqrt(3)*standard_deviation*[-1 1], ...
    'ErrorSD_m',standard_deviation,'ErrorVariance_m2',standard_deviation^2, ...
    'epsilon_c_m',epsilon_c,'CableLength_m',length_input,'EvaluationIndex',evaluation_idx, ...
    'SampleMeanError_m',mean(epsilon_c(evaluation_idx)), ...
    'SampleErrorSD_m',std(epsilon_c(evaluation_idx),0), ...
    'SampleErrorVariance_m2',var(epsilon_c(evaluation_idx),0));
end
